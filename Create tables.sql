-- ==========================
-- TABLA: HDK_TICKET
-- ==========================
CREATE TABLE HDK_TICKET (
    TIC_Ticket              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TIC_Asunto              VARCHAR2(100) NOT NULL,
    TIC_Descripcion         VARCHAR2(300),
    TIC_Estado              VARCHAR2(50) NOT NULL,
    TIC_Prioridad           VARCHAR2(50) NOT NULL,
    TIC_SLA                 NUMBER,
    TIC_FechaHCreacion      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    TIC_UsuarioCreacion     NUMBER NOT NULL, -- FK -> HDK_USUARIO
    TIC_FechaHInicioAtencion TIMESTAMP,
    TIC_TecnicoInicioAtencion NUMBER,        -- FK -> HDK_USUARIO
    TIC_FechaHFinAtencion   TIMESTAMP,
    TIC_FinAtencion  NUMBER,          -- FK -> HDK_USUARIO
    TIC_Satisfaccion        NUMBER(1),       -- escala 1-5
    TIC_SatisfaccionComentario VARCHAR2(500)
);

-- ==========================
-- TABLA: HDK_TICKET_COMENTARIOS
-- ==========================
CREATE TABLE HDK_TICKET_COMENTARIOS (
    COM_Comentario  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COM_Contenido   VARCHAR2(300) NOT NULL,
    USR_Usuario     NUMBER NOT NULL, -- FK -> HDK_USUARIO
    TIC_Ticket      NUMBER NOT NULL  -- FK -> HDK_TICKET
);

-- ==========================
-- TABLA: HDK_TICKET_REPUESTOS
-- ==========================
CREATE TABLE HDK_TICKET_REPUESTOS (
    TRP_Repuesto    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TIC_Ticket      NUMBER NOT NULL, -- FK -> HDK_TICKET
    REP_Repuesto    VARCHAR2(100) NOT NULL,
    TRP_Cantidad    NUMBER(5) DEFAULT 1,
    TRP_Descripcion VARCHAR2(300)
);

-- ==========================
-- TABLA: HDK_TICKET_EVIDENCIA
-- ==========================
CREATE TABLE HDK_TICKET_EVIDENCIA (
    TEV_Evidencia   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TIC_Ticket      NUMBER NOT NULL, -- FK -> HDK_TICKET
    TEV_Ubicacion   VARCHAR2(500)   -- ruta en disco/URL
);

-- ==========================
-- TABLA: HDK_USUARIO
-- ==========================
CREATE TABLE HDK_USUARIO (
    USR_Usuario     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USR_Nombre      VARCHAR2(200) NOT NULL,
    USR_Correo      VARCHAR2(150) UNIQUE NOT NULL,
    USR_Telefono    VARCHAR2(20),
    USR_Extension   VARCHAR2(10),
    DEP_Departamento VARCHAR2(100),
    USR_Ubicacion   VARCHAR2(200),
    USR_Equipo      VARCHAR2(100),
    USR_Password    VARCHAR2(200) NOT NULL,
    USR_Activo      CHAR(1) DEFAULT 'S' CHECK (USR_Activo IN ('S','N')),
    USR_Rol         VARCHAR2(50) NOT NULL
);

-- ==========================
-- TABLA: HDK_CATEGORIA
