-- ==========================
-- TABLA: HDK_PERIODOS
-- ==========================
CREATE TABLE HDK_PERIODOS (
    PER_Periodo     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PER_Nombre      VARCHAR2(150) NOT NULL,
    PER_Descripcion VARCHAR2(300),
    PER_FechaDesde  DATE NOT NULL,
    PER_FechaHasta  DATE,
    PER_Activo      CHAR(1) DEFAULT 'S' CHECK (PER_Activo IN ('S','N'))
);

